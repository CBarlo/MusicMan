@app.route('/api/wifi/connect', methods=['POST'])
def api_wifi_connect():
    data = request.get_json() or {}
    ssid = data.get('ssid', '').strip()
    password = data.get('password', '').strip()
    conn_name = data.get('conn_name', '').strip()  # connect a saved profile by name
    if not ssid and not conn_name:
        return jsonify({'ok': False, 'error': 'No SSID'}), 400
    if conn_name:
        # Reconnect a saved profile — no password needed
        out, rc = _nmcli('connection', 'up', conn_name, timeout=30)
        return jsonify({'ok': rc == 0, 'error': out if rc != 0 else None})
    # Connecting by SSID: delete any stale saved profile first so nmcli
    # doesn't silently reuse the old one (ignoring the new password).
    saved_out, _ = _nmcli('-t', '-f', 'NAME,TYPE', 'connection', 'show')
    for line in saved_out.splitlines():
        p = _nmcli_parse(line, 2)
        if len(p) >= 2 and p[1] == '802-11-wireless':
            ssid_out, _ = _nmcli('-g', '802-11-wireless.ssid', 'connection', 'show', p[0])
            if ssid_out.strip() == ssid:
                _nmcli('connection', 'delete', p[0])
    args = ['device', 'wifi', 'connect', ssid, 'ifname', 'wlan0']
    if password:
        args += ['password', password]
    out, rc = _nmcli(*args, timeout=30)
    return jsonify({'ok': rc == 0, 'error': out if rc != 0 else None})

