def _fire_crowd_strip_leds(fraction, cfg):
    """Push a VU-meter fill to crowd_lights via WLED UDP realtime (DRGB protocol).
    Sends raw per-LED colors — no segment management, no HTTP overhead, no drops."""
    light_ids  = cfg.get('crowd_lights', [])
    if not light_ids:
        return
    strip_len  = max(1, int(cfg.get('crowd_strip_len', 60)))
    num_strips = max(1, int(cfg.get('crowd_num_strips', 1)))
    nodes_map  = {n['id']: n.get('ip') for n in cfg.get('pole_nodes',   []) if n.get('ip')}
    wled_map   = {d['id']: d.get('ip') for d in cfg.get('wled_devices', []) if d.get('ip')}
    ip_map     = {**nodes_map, **wled_map}

    r, g, b = [int(round(c)) for c in _crowd_color_rgb(cfg, fraction)]
    n_lit   = round(strip_len * fraction)

    # Build pixel array: n_lit LEDs per strip lit, rest black
    total  = num_strips * strip_len
    pixels = bytearray(total * 3)   # initialized to all zeros (black)
    for i in range(num_strips):
        base = i * strip_len
        for j in range(n_lit):
            idx = (base + j) * 3
            pixels[idx]     = r
            pixels[idx + 1] = g
            pixels[idx + 2] = b

    # WLED DRGB realtime protocol: [0x02, timeout×100ms, R0,G0,B0, R1,G1,B1, ...]
    packet = bytes([0x02, 20]) + bytes(pixels)   # 20 × 100ms = 2s revert timeout

    for lid in light_ids:
        ip = ip_map.get(lid)
        if ip:
            try:
                _wled_udp_sock.sendto(packet, (ip, 19446))
            except Exception:
                pass

