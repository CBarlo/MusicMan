def wled_set_scene(scene_id):
    """Apply a lighting scene to all WLED devices."""
    global _scene_apply_epoch
    _scene_apply_epoch += 1
    my_epoch = _scene_apply_epoch
    scenes = {s['id']: s for s in config.get('scenes', [])}
    if scene_id not in scenes:
        log.warning(f"Scene not found: {scene_id}")
        return
    scene = scenes[scene_id]
    devices = {d['id']: d for d in config.get('wled_devices', [])}
    zones = scene.get('zones', {})
    def send_zone(device_id, seg_id, effect, color=None, brightness=75, speed=50):
        if device_id not in devices:
            return
        ip = devices[device_id]['ip']
        _WLED_FX = {'solid': 0, 'fire': 35, 'rainbow': 9, 'strobe': 11,
                    'fade': 7, 'theater': 15, 'twinkle': 44}
        fx_id = _WLED_FX.get(effect)
        if fx_id is None:
            log.warning(f"WLED: unknown effect {effect!r} for {device_id}, falling back to solid")
            fx_id = 0
        payload = {
            'seg': [{
                'id': seg_id,
                'on': brightness > 0,
                'bri': int(brightness * 2.55),
                'fx': fx_id,
                'sx': speed,
            }]
        }
        if color:
            r, g, b = int(color[1:3], 16), int(color[3:5], 16), int(color[5:7], 16)
            payload['seg'][0]['col'] = [[r, g, b]]
        if _scene_apply_epoch != my_epoch:
            return  # a newer scene apply has already started — don't send a stale color
        try:
            requests.post(f"http://{ip}/json/state", json=payload, timeout=0.5)
        except Exception as e:
            log.warning(f"WLED {device_id} unreachable: {e}")
    threads = []
    for zone_key, zone_cfg in zones.items():
        if '_pole' in zone_key:
            parts = zone_key.split('_pole_')
            device_id = parts[0] + '_pole' if len(parts) > 1 else zone_key
            seg_name = parts[1] if len(parts) > 1 else 'main'
            device = devices.get(device_id)
            if device:
                seg_id = next((s['id'] for s in device.get('segments', [])
                               if s['name'] == seg_name), 0)
                t = threading.Thread(
                    target=send_zone,
                    args=(device_id, seg_id,
                          zone_cfg.get('effect', 'solid'),
                          zone_cfg.get('color'),
                          zone_cfg.get('brightness', 75),
                          zone_cfg.get('speed', 50)),
                    daemon=True
                )
                threads.append(t)
        else:
            t = threading.Thread(
                target=send_zone,
                args=(zone_key, 0,
                      zone_cfg.get('effect', 'solid'),
                      zone_cfg.get('color'),
                      zone_cfg.get('brightness', 75),
                      zone_cfg.get('speed', 50)),
                daemon=True
            )
            threads.append(t)
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=0.6)   # tighter than original 1.0s; matches the 0.5s HTTP timeout

    # Apply pole flashlight modes — run in background so BLE latency doesn't block the caller
    def _apply_pole_lights():
        from SolixBLE.states import LightStatus
        _ls_map = {'off': LightStatus.OFF, 'low': LightStatus.LOW, 'high': LightStatus.HIGH, 'sos': LightStatus.SOS}
        for pole_label, mode in scene.get('poles', {}).items():
            ls = _ls_map.get((mode or '').lower())
            if ls is None:
                continue
            addr = next((u['address'] for u in config.get('battery_units', []) if u['label'] == pole_label), None)
            if addr:
                ok, err = _batt_cmd(addr, lambda d, _ls=ls: d.set_light_mode(_ls))
                if not ok:
                    log.warning(f'Scene pole light [{pole_label}]: {err}')
    threading.Thread(target=_apply_pole_lights, daemon=True).start()

    # Apply DMX fixture values to pole nodes — one thread per node so a
    # slower/weaker connection on one pole doesn't delay another (nodes were
    # previously sent sequentially in a single thread, and a tight 0.5s
    # timeout on a marginal WiFi link could abort mid-transfer, leaving the
    # ESP32 parsing a truncated JSON payload — manifesting as random-looking
    # colors on whichever node has a weaker connection). 2s matches the
    # timeout already used by Admin's manual per-fixture test fire, which
    # has never shown this problem.
    def _apply_dmx_node(node_id, fixtures_vals, node, fixture_types):
        global _last_scene_dmx
        fixture_defs = {f['id']: f for f in node.get('fixtures', [])}
        payload_raw = []
        for fix_id, channels in fixtures_vals.items():
            if not channels:
                continue
            fix = fixture_defs.get(fix_id)
            if not fix:
                continue
            dim_mask = _build_dim_mask(fix, fixture_types)
            payload_raw.append({'start': fix['start'], 'channels': list(channels),
                                'dim_mask': dim_mask})
        if payload_raw and _scene_apply_epoch == my_epoch:
            _last_scene_dmx[node_id] = payload_raw
            scaled = [{'start': f['start'],
                       'channels': _dim_channels(f['channels'], _master_dim, f['dim_mask'])}
                      for f in payload_raw]
            try:
                requests.post(f"http://{node['ip']}/dmx",
                              json={'fixtures': scaled}, timeout=2)
            except Exception as e:
                log.warning(f"Pole node {node_id} DMX error: {e}")

    dmx_block = scene.get('dmx', {})
    if dmx_block:
        _all_pole_nodes = config.get('pole_nodes', [])
        _nodes_by_id    = {n['id']: n for n in _all_pole_nodes}
        _fixture_types  = config.get('fixture_types', {})
        # "Pole B follows Pole A": scene stores only the leader (first pole
        # node)'s values; every other node's fixtures are computed here from
        # the leader's, matched by fixture id — not saved/duplicated, so
        # editing the leader's look later automatically carries through on
        # the next fire with no re-sync step needed.
        if scene.get('dmx_poles_match') and _all_pole_nodes:
            leader_id = _all_pole_nodes[0]['id']
            leader_vals = dmx_block.get(leader_id, {})
            dmx_block = {leader_id: leader_vals}
            for node in _all_pole_nodes[1:]:
                dmx_block[node['id']] = dict(leader_vals)
        for node_id, fixtures_vals in dmx_block.items():
            node = _nodes_by_id.get(node_id)
            if not node or not node.get('ip'):
                continue
            threading.Thread(target=_apply_dmx_node,
                              args=(node_id, fixtures_vals, node, _fixture_types),
                              daemon=True).start()

    # Cancel any running DMX animation, then start a new one if this scene defines one
    global _dmx_anim_stop
    _dmx_anim_stop.set()
    _dmx_anim_stop = threading.Event()

    # Fire WLED preset on all pole nodes if scene specifies one — one thread
    # per node so they all receive the command at essentially the same
    # moment, instead of node 2 waiting for node 1's HTTP call to finish.
    wled_preset = scene.get('wled_preset')
    wled_preset_by_node = scene.get('wled_preset_by_node') or {}
    if wled_preset is not None or wled_preset_by_node:
        _pole_nodes = config.get('pole_nodes', [])
        def _fire_one(ip, ps):
            if _scene_apply_epoch != my_epoch:
                return
            _wled_fire_preset(ip, ps)
        for node in _pole_nodes:
            ip = node.get('ip')
            if not ip:
                continue
            # A per-node override wins if this scene has one for this node;
            # otherwise every node falls back to the shared preset.
            ps = wled_preset_by_node.get(node['id'], wled_preset)
            if ps is None:
                continue
            threading.Thread(target=_fire_one, args=(ip, ps), daemon=True).start()

    # Start DMX animation loop if scene defines one
    dmx_anim = scene.get('dmx_animation')
    if dmx_anim and dmx_anim.get('frames'):
        transition_s = (dmx_anim.get('interval_ms') or 400) / 1000.0
        frames       = dmx_anim['frames']
        nodes_map    = {n['id']: n for n in config.get('pole_nodes', [])}
        # fixture_types is stored as a dict keyed by type name (see the
        # working usage a few lines up, config.get('fixture_types', {})) —
        # this was iterating it as if it were a list, which yields its
        # string keys, not the type dicts, and crashed every time a scene
        # with a DMX animation fired.
        fixture_types_snap = dict(config.get('fixture_types', {}))
        stop_ev      = _dmx_anim_stop
        def _run_dmx_anim(_frames=frames, _nodes=nodes_map, _stop=stop_ev, _tv=transition_s,
                          _fixture_types=fixture_types_snap):
            global _dmx_anim_active
            _dmx_anim_active = True
            STEP_S  = 0.04  # 40 ms per step (~25 Hz)
            n_steps = max(1, round(_tv / STEP_S))

            # Tracks which nodes currently have a DMX POST in flight. Without
            # this, a node that takes even slightly longer than one 40ms step
            # to respond (very plausible over WiFi) accumulates a growing
            # backlog of overlapping requests — and since HTTP responses can
            # land out of order, a newer request can be overtaken by an
            # older, now-stale one completing later, applying a stale frame
            # after a newer one. That's what "wonky after a couple of
            # cycles" was: the backlog needs a few seconds to build up
            # before it's visible, then it only gets worse. A real-time loop
            # like this should drop a step for a busy node rather than queue
            # it — the next step 40ms later supersedes it anyway.
            _inflight      = set()
            _inflight_lock = threading.Lock()

            def _send_one(node, payload, node_id):
                try:
                    requests.post(f"http://{node['ip']}/dmx",
                                  json={'fixtures': payload}, timeout=2)
                except Exception:
                    pass
                finally:
                    with _inflight_lock:
                        _inflight.discard(node_id)

            def _send(frame):
                # Fire each node in its own thread — this loop runs at ~25Hz,
                # and blocking on a slow/marginal node's HTTP response here
                # would stall the whole animation's timing, backing up steps
                # and then bursting them out once the slow request finally
                # returns (looks exactly like fast strobing on the affected
                # node). Firing and moving on keeps the step timer accurate
                # regardless of how any one node's connection is behaving.
                for node_id, fix_vals in frame.items():
                    node = _nodes.get(node_id)
                    if not node or not node.get('ip'):
                        continue
                    with _inflight_lock:
                        if node_id in _inflight:
                            continue  # previous send to this node still in flight — drop this step
                        _inflight.add(node_id)
                    fix_map = {f['id']: f for f in node.get('fixtures', [])}
                    payload = []
                    for fix_id, channels in fix_vals.items():
                        fix = fix_map.get(fix_id)
                        if fix and channels:
                            mask = _build_dim_mask(fix, _fixture_types)
                            payload.append({'start': fix['start'],
                                            'channels': _dim_channels(channels, _master_dim, mask)})
                    if payload:
                        threading.Thread(target=_send_one, args=(node, payload, node_id), daemon=True).start()
                    else:
                        with _inflight_lock:
                            _inflight.discard(node_id)

            def _interp(fa, fb, t):
                result = {}
                for node_id, fix_vals in fa.items():
                    result[node_id] = {}
                    fb_node = fb.get(node_id, {})
                    for fix_id, ch_a in fix_vals.items():
                        ch_b = (fb_node.get(fix_id) or ch_a)
                        ch_b = (ch_b + ch_a)[:len(ch_a)]  # pad/trim to same length
                        result[node_id][fix_id] = [
                            int(round(a + (b - a) * t)) for a, b in zip(ch_a, ch_b)
                        ]
                return result

            try:
                if len(_frames) == 1:
                    _send(_frames[0])
                    _stop.wait()
                    return

                fi = 0
                while not _stop.is_set():
                    fa = _frames[fi % len(_frames)]
                    fb = _frames[(fi + 1) % len(_frames)]
                    for step in range(n_steps):
                        if _stop.is_set():
                            return
                        _send(_interp(fa, fb, step / n_steps))
                        _stop.wait(STEP_S)
                    fi += 1
            finally:
                _dmx_anim_active = False

        threading.Thread(target=_run_dmx_anim, daemon=True).start()

    global current_scene
    current_scene = scene_id
    log.info(f"Scene applied: {scene_id}")
    broadcast('scene_changed', {'scene': scene_id})

