def _build_dim_mask(fix, fixture_types):
    """True per channel = dimmable (no presets). False = control channel (MODE, EFFECT…)."""
    type_def = fixture_types.get(fix.get('type', ''), {})
    ch_defs  = type_def.get('ch_defs', [])
    mask = [not bool(ch.get('presets')) for ch in ch_defs]
    ch_count = fix.get('channels', len(mask))
    while len(mask) < ch_count:
        mask.append(True)
    return mask[:ch_count]

def _dim_channels(channels, dim, mask=None):
    """Scale only dimmable channels; leave control channels at their raw value."""
    if mask is None:
        mask = [True] * len(channels)
    return [int(v * dim) if mask[i] else int(v) for i, v in enumerate(channels)]

def _walkup_color_anim(preset_num, color1_hex, color2_hex, cancel_event, cfg):
    """Fire crowd-light animation for a circle walkup. Sends ONE command and holds.
    If preset_num is set, fires that WLED preset (user-configured in WLED UI).
    Otherwise falls back to Theater Chase built-in effect using the circle's colours."""
