@app.route('/api/health')
def api_health():
    import psutil

    # Pi vitals
    cpu_temp = None
    try:
        temps = psutil.sensors_temperatures()
        for entries in (temps or {}).values():
            if entries:
                cpu_temp = round(entries[0].current, 1)
                break
    except Exception:
        pass
    disk = psutil.disk_usage('/')
    mem  = psutil.virtual_memory()

    def streamdeck_ready():
        """Whether the deck has actually connected and loaded real show data
        recently, not just whether the systemd unit is still running — a
        process stuck retrying against a slow/restarting musicman.service
        stays 'active' the whole time, which used to show as healthy."""
        try:
            status = json.loads((Path(__file__).parent / 'logs' / 'streamdeck_status.json').read_text())
            return bool(status.get('ready')) and (time.time() - status.get('ts', 0)) < 90
        except Exception:
            return False

    # Service status
    def svc_ok(name):
        try:
            r = subprocess.run(['systemctl', 'is-active', name],
                               capture_output=True, text=True, timeout=2)
            return r.stdout.strip() == 'active'
        except Exception:
            return False

    def proc_ok(pattern):
        try:
            r = subprocess.run(['pgrep', '-f', pattern],
                               capture_output=True, timeout=2)
            return r.returncode == 0
        except Exception:
            return False

    # Audio
    audio_ok = pygame.mixer.get_init() is not None

    # WebSocket clients
    with ws_lock:
        total_ws  = len(ws_clients)
        ips_snap  = dict(ws_client_ips)

    # localhost = streamdeck + display kiosk; non-localhost = iPad/tablet
    remote_ips = [ip for ip in ips_snap if not ip.startswith('127.') and ip != 'unknown']

    # Network device checks — run in parallel threads
    pole_results = []
    wled_results = []
    results_lock = threading.Lock()

    def _check(url, record, lst):
        try:
            t0 = time.time()
            requests.get(url, timeout=1.5)
            record['ok'] = True
            record['ms'] = round((time.time() - t0) * 1000)
        except Exception:
            record['ok'] = False
            record['ms'] = None
        with results_lock:
            lst.append(record)

    threads = []
    for node in config.get('pole_nodes', []):
        ip = node.get('ip', '')
        rec = {'id': node.get('id'), 'name': node.get('name') or node.get('id'), 'ip': ip}
        if ip:
            t = threading.Thread(target=_check, args=(f'http://{ip}/json/info', rec, pole_results), daemon=True)
        else:
            rec.update({'ok': False, 'ms': None})
            pole_results.append(rec)
            continue
        threads.append(t); t.start()

