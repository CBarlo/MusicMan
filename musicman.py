def _sg_find_file(sg_dir, slot):
    """Return (filename, ext) if file exists for slot, else (None, None)."""
    exts = _SG_IMG_EXTS if slot in _SG_IMAGE_SLOTS else _SG_AUD_EXTS
    for ext in exts:
        f = sg_dir / f'{slot}.{ext}'
        if f.exists():
            return f'{slot}.{ext}', ext
    return None, None

