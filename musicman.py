def _countdown_led_devices(countdown_cfg):
    """Return WLED device dicts with total_leds+strips_per_pole set, filtered by countdown_cfg."""
    cfg = load_config()
    ids = countdown_cfg.get('countdown_led_devices') or []
    devs = [d for d in cfg.get('wled_devices', [])
            if (not ids or d.get('id') in ids)
            and d.get('ip') and d.get('total_leds') and d.get('strips_per_pole')]
    return devs

def _update_countdown_leds(remaining, warning_secs, countdown_cfg):
    """Push a two-segment yellow→red fill to each configured WLED device."""
    if warning_secs <= 0:
        return
    fraction = max(0.0, min(1.0, remaining / warning_secs))
    r_val, g_val = 255, int(255 * fraction)
    for dev in _countdown_led_devices(countdown_cfg):
        ip           = dev['ip'].strip()
        total_leds   = int(dev['total_leds'])
        strips       = int(dev['strips_per_pole'])
        leds_per_strip = total_leds // strips
        n_lit = round(leds_per_strip * fraction)
        segs = []
        for i in range(strips):
            base   = i * leds_per_strip
            seg_id = i * 2
            if n_lit > 0:
                segs.append({'id': seg_id, 'start': base, 'stop': base + n_lit,
                             'col': [[r_val, g_val, 0]], 'fx': 0, 'on': True})
            segs.append({'id': seg_id + 1, 'start': base + n_lit,
                         'stop': base + leds_per_strip,
                         'col': [[0, 0, 0]], 'fx': 0, 'on': True})
        threading.Thread(target=_wled_post, args=(ip, {'seg': segs}), daemon=True).start()

def _clear_countdown_leds(countdown_cfg):
    """Restore WLED segment layout after countdown by re-firing the last known preset.
    Falls back to brightness-off if no preset has been fired on that device."""
    for dev in _countdown_led_devices(countdown_cfg):
        ip = dev['ip'].strip()
        last = _wled_last_preset.get(ip)
        if last is not None:
            threading.Thread(target=_wled_fire_preset, args=(ip, last), daemon=True).start()
        else:
            threading.Thread(target=_wled_post, args=(ip, {'bri': 0}), daemon=True).start()

