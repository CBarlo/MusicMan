@app.route('/api/games/chairs/start', methods=['POST'])
def api_games_chairs_start():
    global chairs_state, _chairs_stop_token, _chairs_audio_session
    data          = request.json or {}
    config_id     = data.get('config_id', '')
    cfg_data, name = _chairs_config_data(config_id)
    song = data.get('song') or cfg_data.get('song', '')
    if not song:
        return jsonify({'ok': False, 'error': 'No song selected'}), 400
    fp = (ASSETS_DIR / 'music' / song).resolve()
    if not fp.is_relative_to((ASSETS_DIR / 'music').resolve()) or not fp.exists():
        return jsonify({'ok': False, 'error': 'Song file not found'}), 404

    is_first_round = chairs_state['round'] == 0
    # Only resume in place if it's the same song, mid-game, and nothing else has
    # touched the shared music channel (walkup, macro, console) since we paused it.
    resume = (not is_first_round
              and chairs_state.get('song') == song
              and _audio_session == _chairs_audio_session)

    with _chairs_lock:
        _chairs_stop_token += 1
        my_token = _chairs_stop_token
        chairs_state['round']       += 1
        chairs_state['playing']      = True
        chairs_state['config_id']    = config_id
        chairs_state['config_name']  = name
        chairs_state['song']         = song
        chairs_state['song_label']   = Path(song).stem

    if resume:
        pygame.mixer.music.unpause()
        audio_state['paused'] = False
        broadcast('audio_state', audio_state)
    else:
        # An operator-picked song (via the Console dropdown) needs its own trim,
        # not whatever offset was tuned for the config's original song — so an
        # explicit override always wins, even 0 (no trim), over the config default.
        offset_override = data.get('song_start_offset')
        start_pos = float(offset_override) if offset_override is not None else float(cfg_data.get('song_start_offset', 0) or 0)
        def _play():
            global _chairs_audio_session
            play_audio(str(fp), loops=-1, start_pos=start_pos, crossfade_ms=0)
            _chairs_audio_session = _audio_session
        threading.Thread(target=_play, daemon=True).start()

    broadcast('chairs_state', chairs_state)

    # Intro Game Entry / Screen fields fire once at GO LIVE (see /api/games/launch),
    # not here — the audience-facing screen shouldn't wait on the operator hitting START.

    scene_id = cfg_data.get('start_scene')
    if scene_id:
        threading.Thread(target=wled_set_scene, args=(scene_id,), daemon=True).start()

    if cfg_data.get('auto_stop', True):
        lo = float(cfg_data.get('min_interval', 15) or 15)
        hi = float(cfg_data.get('max_interval', 45) or 45)
        if hi < lo:
            lo, hi = hi, lo
        delay = random.uniform(lo, hi)
        def _auto_stop():
            time.sleep(delay)
            with _chairs_lock:
                if _chairs_stop_token != my_token:
                    return
            _chairs_do_stop(cfg_data)
        threading.Thread(target=_auto_stop, daemon=True).start()

    return jsonify({'ok': True, 'round': chairs_state['round']})

