def api_macro_run():
    name   = request.args.get('name', '')
    cfg    = config
    macros = {m['id']: m for m in cfg.get('macros', [])}
    if name not in macros:
        log.warning(f"Macro not found: {name}")
        return jsonify({'ok': False, 'error': f'Macro not found: {name}'}), 404
    # Check if this macro is part of the show flow and broadcast which step fired
    macro_obj = macros[name]
    step_name  = macro_obj.get('name', name)
    step_color = '#F5A623'
    for idx, entry in enumerate(cfg.get('show_flow', [])):
        if entry.get('macro_id') == name:
            step_name  = entry.get('name') or step_name
            step_color = entry.get('color', step_color)
            broadcast('show_step', {'index': idx, 'macro_id': name, 'name': step_name, 'desc': entry.get('desc', '')})
            break
    # Always update projector display when a macro fires
    disp = {'name': step_name, 'color': step_color}
    img  = macro_obj.get('display_image', '')
    if img:
        disp['image'] = f'/assets/macros/{name}/{img}'
    _ensure_display_for('display_step', disp)
    global _macro_cancel
    _macro_cancel.set()
    _macro_cancel = threading.Event()
    threading.Thread(target=execute_macro, args=(macro_obj, _macro_cancel), daemon=True).start()
    return jsonify({'ok': True})

def _walkup_preload_payload_for_item(item_type, target_id, cfg):
    """Return a walkup_preload payload dict for a circle or role, or None if not found."""
    item_key = 'circles' if item_type == 'circle' else 'roles'
    items    = {i['id']: i for i in cfg.get(item_key, [])}
    item     = items.get(target_id)
    if not item:
        return None
    assets = item.get('assets', {})
    return {
        'type':            item_type,
        'id':              target_id,
        'animation_intro': assets.get('animation_intro', ''),
        'animation':       assets.get('animation', ''),
    }

def _get_next_walkup_preload(cfg, idx):
    """Return walkup_preload payload for the first walkup after show_flow[idx], skipping game steps."""
    if idx is None:
        return None
    flow = cfg.get('show_flow', [])
    if idx + 1 >= len(flow):
        return None
    nxt      = flow[idx + 1]
    nxt_type = nxt.get('type', 'macro')
    if nxt_type == 'circle':
        return _walkup_preload_payload_for_item('circle', nxt.get('target_id', ''), cfg)
    elif nxt_type == 'role':
        return _walkup_preload_payload_for_item('role', nxt.get('target_id', ''), cfg)
    elif nxt_type == 'macro':
        macro_id  = nxt.get('macro_id', '')
        macros    = {m['id']: m for m in cfg.get('macros', [])}
        macro_obj = macros.get(macro_id)
        if macro_obj:
            for step in macro_obj.get('steps', []):
                if step.get('action') == 'walkup_circle':
                    return _walkup_preload_payload_for_item('circle', step.get('circle_id', ''), cfg)
                elif step.get('action') == 'walkup_role':
                    return _walkup_preload_payload_for_item('role', step.get('role_id', ''), cfg)
    elif nxt_type in ('game', 'vs_card'):
        # Skip non-walkup steps and preload for whatever follows
        return _get_next_walkup_preload(cfg, idx + 1)
    return None


@app.route('/api/show/fire')
def api_show_fire():
    """Fire a show-flow step by index. Delegates to macro/run logic."""
    try:
        idx = int(request.args.get('index', -1))
    except (TypeError, ValueError):
        return jsonify({'ok': False, 'error': 'invalid index'}), 400
    cfg  = config
    flow = cfg.get('show_flow', [])
    if idx < 0 or idx >= len(flow):
        return jsonify({'ok': False, 'error': 'index out of range'}), 404

    entry     = flow[idx]
    step_type = entry.get('type', 'macro')
    step_desc = entry.get('desc', '')
    if step_type == 'circle':
        target_id = entry.get('target_id', '')
        broadcast('show_step', {'index': idx, 'name': entry.get('name', target_id), 'desc': step_desc})
        _navigate_home_if_needed()
        threading.Thread(target=fire_walkup, kwargs={'circle_id': target_id, 'show_flow_idx': idx}, daemon=True).start()
    elif step_type == 'role':
        target_id = entry.get('target_id', '')
        broadcast('show_step', {'index': idx, 'name': entry.get('name', target_id), 'desc': step_desc})
        _navigate_home_if_needed()
        threading.Thread(target=fire_walkup, kwargs={'role_id': target_id, 'show_flow_idx': idx}, daemon=True).start()
    elif step_type == 'game':
        game_type_id   = entry.get('game_type_id', '')
        game_config_id = entry.get('game_config_id', '')
        gt             = GAME_TYPES.get(game_type_id, {})
        step_name      = entry.get('name') or gt.get('label', 'Game')
        ctrl_url, disp_url = _launch_game(game_type_id, game_config_id)
        broadcast('show_step', {'index': idx, 'name': step_name, 'desc': step_desc, 'type': 'game'})
        broadcast('launch_game', {
            'game_type_id':   game_type_id,
            'game_config_id': game_config_id,
            'controller_url': ctrl_url,
            'display_url':    disp_url,
            'name':           step_name,
        })
    elif step_type == 'vs_card':
        card_id   = entry.get('vs_card_id', '')
        cards     = {c['id']: c for c in load_vs_cards()}
        card      = dict(cards.get(card_id, {}))
        step_name = entry.get('name') or card.get('name', 'VS')
        broadcast('show_step', {'index': idx, 'name': step_name, 'desc': step_desc, 'type': 'vs_card'})
        if card:
            card = _vs_card_resolve_images(card, card_id)
            _ensure_display_for('display_vs_card', card)
        else:
            log.warning(f'show/fire: vs_card not found: {card_id!r}')
    else:
        macro_id  = entry.get('macro_id', '')
        macros    = {m['id']: m for m in cfg.get('macros', [])}
        macro_obj = macros.get(macro_id)
        if not macro_obj:
            log.warning(f'show/fire: macro not found: {macro_id!r}')
            return jsonify({'ok': False, 'error': f'macro not found: {macro_id}'}), 404
        step_name  = entry.get('name') or macro_obj.get('name', macro_id)
        step_color = entry.get('color', '#F5A623')
        broadcast('show_step', {'index': idx, 'macro_id': macro_id, 'name': step_name, 'desc': step_desc})
        disp = {'name': step_name, 'color': step_color}
        img  = macro_obj.get('display_image', '')
        if img:
            disp['image'] = f'/assets/macros/{macro_id}/{img}'
        _ensure_display_for('display_step', disp)
        global _macro_cancel
        _macro_cancel.set()
        _macro_cancel = threading.Event()
        threading.Thread(target=execute_macro, args=(macro_obj, _macro_cancel, idx), daemon=True).start()

    return jsonify({'ok': True})

